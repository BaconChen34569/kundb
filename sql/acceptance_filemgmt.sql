-- ---------- 1. 建库建表（触发文件预分配）----------
CREATE DATABASE fmtest
USE fmtest
CREATE TABLE slots (id INT PRIMARY KEY, name VARCHAR, v INT)
SHOW TABLE FILE slots

-- ---------- 2. 插入三行 ----------
INSERT INTO slots VALUES (1,'aaa',10)
INSERT INTO slots VALUES (2,'bbb',20)
INSERT INTO slots VALUES (3,'ccc',30)
SELECT * FROM slots
SHOW FILE MAP slots 10

-- ---------- 3. 删除中间一行：只做删除标记，不移动数据 ----------
DELETE FROM slots WHERE id = 2
SELECT * FROM slots
-- 槽 1 应显示 DELETED(可复用空位)，且文件里的内容 bbb 还原封不动
SHOW FILE MAP slots 10
SHOW TABLE FILE slots

-- ---------- 4. 插入新行：应住进被删掉留下的第一个空位（槽 1）----------
INSERT INTO slots VALUES (4,'ddd',40)
SELECT * FROM slots
-- 槽 1 重新变成 USED，内容换成 ddd；注意行的物理顺序变成 1 / 4 / 3
SHOW FILE MAP slots 10
SHOW TABLE FILE slots

-- ---------- 5. 更新：在原来的记录位置原地修改 ----------
UPDATE slots SET v = v + 5 WHERE id = 1
SELECT * FROM slots
SHOW FILE MAP slots 10

-- ---------- 6. 再删一行，观察空位累积 ----------
DELETE FROM slots WHERE id = 3
SHOW FILE MAP slots 10
SHOW TABLE FILE slots

-- ---------- 7. OPTIMIZE TABLE：真正回收空位 ----------
OPTIMIZE TABLE slots
SELECT * FROM slots
SHOW FILE MAP slots 10
SHOW TABLE FILE slots

